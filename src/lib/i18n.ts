export interface LanguageMeta {
  id: Lang
  /** Endonym, shown in the picker. */
  label: string
  /** BCP-47 tag for dates and numbers; Arabic is pinned to Latin digits. */
  locale: string
  dir: 'ltr' | 'rtl'
}

/** Offered in this order — Arabic first. */
export const LANGUAGES: LanguageMeta[] = [
  { id: 'ar', label: 'العربية', locale: 'ar-u-nu-latn', dir: 'rtl' },
  { id: 'en', label: 'English', locale: 'en-GB', dir: 'ltr' },
  { id: 'de', label: 'Deutsch', locale: 'de-DE', dir: 'ltr' },
  { id: 'fr', label: 'Français', locale: 'fr-FR', dir: 'ltr' },
]

const DICTS: Record<Lang, Record<Key, string>> = { ar, en, de, fr }

export function languageMeta(lang: Lang): LanguageMeta {
  return LANGUAGES.find((l) => l.id === lang) ?? LANGUAGES[1]
}

export const localeOf = (lang: Lang) => languageMeta(lang).locale
export const directionOf = (lang: Lang) => languageMeta(lang).dir

export type Translator = (key: Key, vars?: Record<string, string | number>) => string

export function translator(lang: Lang): Translator {
  const dict = DICTS[lang] ?? en
  return (key, vars) => {
    let out = dict[key] ?? en[key] ?? String(key)
    if (vars) {
      for (const [k, v] of Object.entries(vars)) out = out.replaceAll(`{${k}}`, String(v))
    }
    return out
  }
}

